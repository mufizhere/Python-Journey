# 1. What is a Comment?
# - A comment is text written in a Python program that is not executed by Python.


# 2. Comments are used to:
# - Explain the code
# - Add notes for programmers
# - Make code easier to understand
# - Add information such as author name or date


# Types of Comments in Python:
# - Single-Line Comments
# - Multiline Comments


# 1. Single-Line Comments:
# - single-line comment starts with the # symbol.
# - Python ignores everything written after # on that line.

# Example:
# This is a single-line comment
print("Hello Python!")


# 2. Multiline Comments:
# - Python does not have a separate multiline comment syntax.
# - Triple quotes can be used to write text across multiple lines.
# - Triple single quotes or triple double quotes can be used.

# Example:
"""
This is a multiline
text written across
multiple lines.
"""
print("Hello Python!")